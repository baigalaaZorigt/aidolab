#!/usr/bin/env python3
"""Custom domains on the gateway (runs as root, stdlib only). Started by aidolab-domains.path/.timer.

Input:  /srv/aidolab/data/domains/wanted, "<domain> <slug>" per line, written by the worker
        (aidolab user) only for domains whose TXT ownership record is verified.
Output: Let's Encrypt certificate per domain (HTTP-01, webroot), an nginx server block per domain,
        and /srv/aidolab/data/domains-status.json for the dashboard.

The input comes from a less trusted user, so every line is re-validated and only [a-z0-9.-]
ever reaches a command line or an nginx file.
"""
import json
import os
import re
import shutil
import subprocess
import time
from pathlib import Path

WANTED = Path("/srv/aidolab/data/domains/wanted")
STATUS = Path("/srv/aidolab/data/domains-status.json")
CONF_DIR = Path("/etc/nginx/aidolab-domains")
LIVE = Path("/etc/letsencrypt/live")
WEBROOT = "/var/www/letsencrypt"
PREFIX = "custom-"  # certbot cert names this script owns
RETRY_AFTER = 30 * 60  # Let's Encrypt allows 5 failed validations per hostname per hour
MAX_DOMAINS = 500

DOMAIN_RE = re.compile(r"^(?=.{4,253}$)(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{1,38}[a-z0-9]$")
PLATFORM = "aidolab.mn"

SERVER = """# Generated by sync-domains.py — do not edit.
server {{
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name {domain};
    ssl_certificate     {live}/fullchain.pem;
    ssl_certificate_key {live}/privkey.pem;
    include /etc/letsencrypt/options-ssl-nginx.conf;
    set $app {slug};
    include /etc/nginx/snippets/aidolab-app-proxy.conf;
}}
"""


def read_wanted() -> dict[str, str]:
    wanted = {}
    try:
        lines = WANTED.read_text().splitlines()[:MAX_DOMAINS]
    except OSError:
        return wanted
    for line in lines:
        parts = line.split()
        if len(parts) != 2:
            continue
        domain, slug = parts
        if (DOMAIN_RE.match(domain) and SLUG_RE.match(slug)
                and domain != PLATFORM and not domain.endswith("." + PLATFORM)):
            wanted[domain] = slug
    return wanted


def read_status() -> dict:
    try:
        return json.loads(STATUS.read_text())
    except (OSError, ValueError):
        return {}


def write_status(status: dict) -> None:
    tmp = STATUS.with_suffix(".tmp")
    tmp.write_text(json.dumps(status, indent=1, sort_keys=True))
    shutil.chown(tmp, "aidolab", "aidolab")
    os.chmod(tmp, 0o640)
    os.replace(tmp, STATUS)


def issue(domain: str) -> str | None:
    """Returns None on success, otherwise a short error for the dashboard."""
    result = subprocess.run(
        ["certbot", "certonly", "--webroot", "-w", WEBROOT, "-d", domain, "--cert-name", PREFIX + domain,
         "--non-interactive", "--agree-tos", "--register-unsafely-without-email",
         "--deploy-hook", "systemctl reload nginx"],
        capture_output=True, text=True, timeout=300)
    if result.returncode == 0:
        return None
    lines = [line.strip() for line in (result.stdout + result.stderr).splitlines() if line.strip()]
    detail = [line for line in lines if "Detail:" in line or "Error" in line or "error" in line]
    return " ".join((detail or lines)[-3:])[:300] or "certbot failed"


def nginx_ok() -> bool:
    return subprocess.run(["nginx", "-t", "-q"], capture_output=True).returncode == 0


def main() -> None:
    wanted = read_wanted()
    old = read_status()
    status, now = {}, int(time.time())
    CONF_DIR.mkdir(exist_ok=True)
    Path(WEBROOT).mkdir(parents=True, exist_ok=True)

    for domain, slug in wanted.items():
        live = LIVE / (PREFIX + domain)
        if not (live / "fullchain.pem").exists():
            prev = old.get(domain, {})
            if not prev.get("ok") and now - prev.get("tried", 0) < RETRY_AFTER:
                status[domain] = prev
                continue
            error = issue(domain)
            if error:
                status[domain] = {"ok": False, "error": error, "tried": now}
                continue
        status[domain] = {"ok": True, "tried": now}

    # Rewrite the server blocks; keep the old set if nginx rejects the new one.
    backup = CONF_DIR.with_name(CONF_DIR.name + ".bak")
    shutil.rmtree(backup, ignore_errors=True)
    shutil.copytree(CONF_DIR, backup)
    for f in CONF_DIR.glob("*.conf"):
        f.unlink()
    for domain, report in status.items():
        if report["ok"]:
            (CONF_DIR / f"{domain}.conf").write_text(
                SERVER.format(domain=domain, slug=wanted[domain], live=LIVE / (PREFIX + domain)))
    if nginx_ok():
        subprocess.run(["systemctl", "reload", "nginx"], check=True)
    else:
        shutil.rmtree(CONF_DIR)
        shutil.move(backup, CONF_DIR)
        for report in status.values():
            if report["ok"]:
                report.update(ok=False, error="nginx тохиргоо алдаатай. Багшид хандана уу.")

    # Certificates of removed domains (only ones this script created).
    for live in LIVE.glob(PREFIX + "*"):
        if live.name.removeprefix(PREFIX) not in wanted:
            subprocess.run(["certbot", "delete", "--cert-name", live.name, "--non-interactive"],
                           capture_output=True, timeout=120)

    write_status(status)


if __name__ == "__main__":
    main()
